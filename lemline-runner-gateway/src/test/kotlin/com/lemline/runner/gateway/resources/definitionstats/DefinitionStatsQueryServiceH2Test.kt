package com.lemline.runner.gateway.resources.definitionstats

import com.lemline.runner.common.config.ANALYTICS_LIFECYCLE_EVENTS_TABLE
import com.lemline.runner.common.config.ANALYTICS_TYPE_H2
import com.lemline.runner.common.test.H2TestDatabaseConfig
import javax.sql.DataSource
import org.junit.jupiter.api.AfterAll
import org.junit.jupiter.api.BeforeAll
import org.junit.jupiter.api.DisplayName
import org.junit.jupiter.api.TestInstance

@DisplayName("DefinitionStatsQueryService [H2]")
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class DefinitionStatsQueryServiceH2Test : DefinitionStatsQueryServiceTestBase() {

    private val testDb = H2TestDatabaseConfig()

    override val analyticsType = ANALYTICS_TYPE_H2
    override val qualifiedTable = "\"$ANALYTICS_LIFECYCLE_EVENTS_TABLE\""
    override fun dataSource(): DataSource = testDb.jdbcDataSource

    @BeforeAll
    fun createTable() {
        // Columns read by the stats query, as in the analytics H2 migration.
        dataSource().connection.use { conn ->
            conn.createStatement().use {
                it.execute(
                    """
                    CREATE TABLE $qualifiedTable (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        type VARCHAR(255) NOT NULL,
                        event_time TIMESTAMP WITH TIME ZONE NULL,
                        lemline_workflow_id UUID NULL,
                        lemline_workflow_namespace VARCHAR(255) NULL,
                        lemline_workflow_name VARCHAR(255) NULL,
                        lemline_workflow_version VARCHAR(255) NULL
                    )
                    """.trimIndent()
                )
            }
        }
    }

    @AfterAll
    fun closeDatabase() {
        testDb.close()
    }
}
