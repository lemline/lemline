package com.lemline.runner.cli.config

import com.lemline.runner.common.config.AnalyticsType
import com.lemline.runner.common.config.DatabaseType
import com.lemline.runner.common.config.MessagingType

internal fun defaultAnalytics(messaging: MessagingType, database: DatabaseType): AnalyticsType? = when {
    messaging != MessagingType.SQLITE -> null
    database == DatabaseType.SQLITE -> AnalyticsType.SQLITE
    else -> AnalyticsType.POSTGRESQL
}

/**
 * Generates YAML configuration templates for different messaging and database combinations.
 */
class ConfigTemplateGenerator {

    fun generate(
        messagingType: MessagingType,
        databaseType: DatabaseType,
        analyticsType: AnalyticsType? = null,
    ): String {
        require(messagingType != MessagingType.IN_MEMORY) {
            "IN_MEMORY messaging is not supported for production configurations"
        }
        require(databaseType != DatabaseType.H2) {
            "H2 database is not supported for production configurations"
        }

        val resolvedAnalytics = analyticsType ?: defaultAnalytics(messagingType, databaseType)
        val composeCommand = getDockerComposeCommand(messagingType, databaseType, resolvedAnalytics)
        val messagingDisplay = getDisplayName(messagingType)
        val databaseDisplay = getDisplayName(databaseType)
        // No compose profile starts a broker alone: say which part of it SQLite leaves unused.
        val profileNote = if (databaseType == DatabaseType.SQLITE && messagingType in setOf(MessagingType.KAFKA, MessagingType.RABBITMQ)) {
            "\n|#   (this profile also starts PostgreSQL, which SQLite orchestration does not use)"
        } else {
            ""
        }
        val sqlite = messagingType == MessagingType.SQLITE
        val analytics = when (resolvedAnalytics) {
            AnalyticsType.SQLITE -> "\n" + """
                |  analytics:
                |    type: sqlite
                |    sqlite:
                |      path: analytics.db
            """.trimMargin()
            AnalyticsType.POSTGRESQL -> {
                val name = if (analyticsType == AnalyticsType.POSTGRESQL) "lemline_analytics" else "lemline"
                "\n${postgresSection("analytics", name)}"
            }
            null -> ""
            AnalyticsType.H2 -> error("H2 analytics is not supported in generated configurations")
        }
        val createAnalytics = if (analyticsType == AnalyticsType.POSTGRESQL) {
            "\n|#   docker compose exec postgres createdb -U postgres lemline_analytics"
        } else {
            ""
        }
        val migrate = if (sqlite) "#   LEMLINE_CONFIG=./lemline.yaml lemline migrate --force\n" else ""

        return """
            |# Lemline Configuration: $messagingDisplay + $databaseDisplay
            |# Generated by: lemline config create
            |#
            |# Start infrastructure:
            |#   $composeCommand$profileNote$createAnalytics
            |#
            |# Run Lemline:
            |${migrate}#   LEMLINE_CONFIG=./lemline.yaml lemline listen
            |
            |lemline:
            |${getDatabaseSection(databaseType)}
            |${getMessagingSection(messagingType)}$analytics
            """.trimMargin()
    }

    private fun getDatabaseSection(databaseType: DatabaseType): String {
        return when (databaseType) {
            DatabaseType.POSTGRESQL -> postgresSection("database")

            DatabaseType.MYSQL -> $$"""
                |  database:
                |    mysql:
                |      host: localhost
                |      port: 3306
                |      database: lemline
                |      username: lemline
                |      password: ${LEMLINE_MYSQL_PASSWORD:lemline}
            """.trimMargin()

            DatabaseType.SQLITE -> """
                |  database:
                |    type: sqlite
                |    sqlite:
                |      path: orchestration.db
            """.trimMargin()

            DatabaseType.H2 -> error("H2 database is not supported for production configurations")
        }
    }

    private fun postgresSection(section: String, database: String = "lemline"): String = $$"""
        |  $$section:
        |    postgresql:
        |      host: localhost
        |      port: 5432
        |      database: $$database
        |      username: postgres
        |      password: ${LEMLINE_PG_PASSWORD:postgres}
    """.trimMargin()

    private fun getMessagingSection(messagingType: MessagingType): String {
        return when (messagingType) {
            MessagingType.KAFKA -> """
                |  messaging:
                |    kafka:
                |      brokers: localhost:9092
            """.trimMargin()

            MessagingType.RABBITMQ -> """
                |  messaging:
                |    rabbitmq:
                |      hostname: localhost
                |      port: 5672
                |      username: guest
                |      password: guest
            """.trimMargin()

            MessagingType.PGMQ -> $$"""
                |  messaging:
                |    pgmq:
                |      host: localhost
                |      port: 5432
                |      database: lemline
                |      username: postgres
                |      password: ${LEMLINE_PGMQ_PASSWORD:postgres}
            """.trimMargin()

            MessagingType.SQLITE -> """
                |  messaging:
                |    type: sqlite
                |    sqlite:
                |      path: messaging.db
            """.trimMargin()

            MessagingType.IN_MEMORY -> error("IN_MEMORY messaging is not supported for production configurations")
        }
    }

    private fun getDockerComposeCommand(messagingType: MessagingType, databaseType: DatabaseType, analyticsType: AnalyticsType?): String =
        if (messagingType == MessagingType.SQLITE) {
            when (databaseType) {
                DatabaseType.POSTGRESQL -> "docker compose up -d postgres"
                DatabaseType.MYSQL -> if (analyticsType == AnalyticsType.POSTGRESQL) "docker compose up -d mysql postgres" else "docker compose up -d mysql"
                DatabaseType.SQLITE -> if (analyticsType == AnalyticsType.POSTGRESQL) "docker compose up -d postgres" else "No external services required."
                DatabaseType.H2 -> error("H2 not supported")
            }
        } else {
            val profile = getDockerComposeProfile(messagingType, databaseType)
            val extraPostgres = analyticsType == AnalyticsType.POSTGRESQL && profile in setOf("kafka-mysql", "rabbit-mysql")
            if (extraPostgres) "docker compose --profile $profile up -d\n|#   docker compose up -d postgres"
            else "docker compose --profile $profile up -d"
        }

    private fun getDockerComposeProfile(messagingType: MessagingType, databaseType: DatabaseType): String {
        return when (messagingType) {
            MessagingType.KAFKA -> when (databaseType) {
                DatabaseType.POSTGRESQL, DatabaseType.SQLITE -> "kafka-pg"
                DatabaseType.MYSQL -> "kafka-mysql"
                DatabaseType.H2 -> error("H2 not supported")
            }

            MessagingType.RABBITMQ -> when (databaseType) {
                DatabaseType.POSTGRESQL, DatabaseType.SQLITE -> "rabbit-pg"
                DatabaseType.MYSQL -> "rabbit-mysql"
                DatabaseType.H2 -> error("H2 not supported")
            }

            MessagingType.PGMQ -> when (databaseType) {
                DatabaseType.POSTGRESQL, DatabaseType.SQLITE -> "pgmq"
                DatabaseType.MYSQL -> "pgmq-mysql"
                DatabaseType.H2 -> error("H2 not supported")
            }

            MessagingType.SQLITE, MessagingType.IN_MEMORY -> error("No broker profile for $messagingType")
        }
    }

    private fun getDisplayName(messagingType: MessagingType): String {
        return when (messagingType) {
            MessagingType.KAFKA -> "Kafka"
            MessagingType.RABBITMQ -> "RabbitMQ"
            MessagingType.PGMQ -> "PGMQ"
            MessagingType.SQLITE -> "SQLite"
            MessagingType.IN_MEMORY -> "InMemory"
        }
    }

    private fun getDisplayName(databaseType: DatabaseType): String {
        return when (databaseType) {
            DatabaseType.POSTGRESQL -> "PostgreSQL"
            DatabaseType.MYSQL -> "MySQL"
            DatabaseType.SQLITE -> "SQLite"
            DatabaseType.H2 -> "H2"
        }
    }
}
